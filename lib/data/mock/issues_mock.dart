Issue _issue(
  String id,
  String assetId,
  String title,
  String type,
  String priority,
  String status,
  String reporter,
  DateTime at,
  String location, {
  String description = '',
  String? assignee = PersonIds.rafi,
  DateTime? resolvedAt,
}) {
  return Issue(
    id: id,
    assetId: assetId,
    title: title,
    type: type,
    priority: priority,
    status: status,
    reporterId: reporter,
    reportedAt: at,
    location: location,
    description: description.isEmpty ? '$title. Reported during routine operation.' : description,
    assigneeId: assignee,
    assignedTeam: assignee == null ? null : 'Maintenance Team',
    resolvedAt: resolvedAt,
    timeline: [
      LogEntry(at: at, title: 'Issue reported'),
      if (status != IssueStatus.open)
        LogEntry(at: at.add(const Duration(minutes: 20)), title: 'Status changed to In Progress'),
      if (resolvedAt != null) LogEntry(at: resolvedAt, title: 'Issue resolved'),
    ],
  );
}

