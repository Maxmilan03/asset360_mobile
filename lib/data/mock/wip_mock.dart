Operation _done(String name, String station, int mins, DateTime at) => Operation(
  name: name,
  station: station,
  status: OpStatus.completed,
  expectedMins: mins,
  actualMins: mins,
  startedAt: at.subtract(Duration(minutes: mins)),
  completedAt: at,
);
Operation _pending(String name, String station, int mins) =>
    Operation(name: name, station: station, status: OpStatus.pending, expectedMins: mins);

