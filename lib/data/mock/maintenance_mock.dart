const _corrective = 'Corrective Maintenance';
const _preventive = 'Preventive Maintenance';

List<CheckItem> _items(String prefix, List<String> labels, {int done = 0}) => [
  for (var i = 0; i < labels.length; i++)
    CheckItem(
      code: '$prefix-${i + 1}',
      label: labels[i],
      type: CheckType.tick,
      value: i < done ? CheckItem.done : null,
    ),
];

/// Short standard task list for WOs that aren't shown in detail in the designs.
List<WoTask> _standardTasks(String id, {bool allDone = false, DateTime? doneAt}) {
  final s = allDone ? TaskStatus.completed : TaskStatus.pending;
  WoTask t(int n, String title, List<String> items) => WoTask(
    id: '$id-T$n',
    title: title,
    status: s,
    completedAt: allDone ? doneAt : null,
    checklist: _items('$id-T$n', items, done: allDone ? items.length : 0),
  );
  return [
    t(1, 'Arrival & Safety Check', ['PPE worn', 'Area isolated (LOTO)', 'Permit to work signed']),
    t(2, 'Inspection & Service', ['Visual inspection', 'Clean and lubricate', 'Check fasteners']),
    t(3, 'Testing & Sign-off', ['Functional test', 'Update records', 'Handover to operator']),
  ];
}

List<LogEntry> _created(DateTime at, String by, {String? assignee}) => [
  LogEntry(at: at, title: 'Work order created', by: by),
  if (assignee != null) LogEntry(at: at.add(const Duration(minutes: 5)), title: 'Assigned to $assignee', by: by),
];

